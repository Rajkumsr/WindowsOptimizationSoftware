"""
Apex Windows Optimizer - Storage Maintenance & WinGet Updater Mixin
Provides deep disk cleanup scanning, CleanMgr automation, WinGet package updates,
and shell refresh / DNS cache flushing.
"""

import os
import sys
import time
import tempfile
import winreg
import subprocess
from typing import Dict, List, Tuple
from .base import CREATE_NO_WINDOW


class CleanupMixin:
    # -------------------------------------------------------------
    # 8. Disk & Cache Cleaner (Real, High-Speed Cleaner)
    # -------------------------------------------------------------
    def get_cleanup_targets(self) -> List[Dict[str, str]]:
        windir = os.environ.get("SystemRoot", r"C:\Windows")
        user_temp = tempfile.gettempdir()
        local_app = os.environ.get("LOCALAPPDATA", "")

        return [
            {"id": "win_temp", "name": "Windows System Temp", "path": os.path.join(windir, "Temp"), "desc": "Temporary files generated by OS services"},
            {"id": "user_temp", "name": "User Profile Temp", "path": user_temp, "desc": "Temporary files generated by running user applications"},
            {"id": "softwaredist", "name": "Windows Update Cache", "path": os.path.join(windir, "SoftwareDistribution", "Download"), "desc": "Leftover downloaded Windows update setup files"},
            {"id": "dx_cache", "name": "DirectX Shader Cache", "path": os.path.join(local_app, "D3DSCache") if local_app else "", "desc": "Cached shader binaries that can become bloated"},
            {"id": "delivery_opt", "name": "Delivery Optimization Cache", "path": os.path.join(windir, "ServiceProfiles", "NetworkService", "AppData", "Local", "Microsoft", "Windows", "DeliveryOptimization"), "desc": "Downloaded P2P update bits"},
            {"id": "wer_dumps", "name": "Crash Dumps & Error Reports", "path": os.path.join(local_app, "CrashDumps") if local_app else "", "desc": "Application crash minidumps and logs"},
            {"id": "thumb_cache", "name": "Explorer Thumbnail Cache", "path": os.path.join(local_app, "Microsoft", "Windows", "Explorer") if local_app else "", "desc": "Cached image thumbnails (rebuilt automatically)"},
            {"id": "winsxs", "name": "WinSxS Component Store (DISM)", "path": os.path.join(windir, "WinSxS"), "desc": "Superseded Windows update components & service pack backups (purged via DISM)"}
        ]

    def scan_cleanup_sizes(self) -> Dict[str, Tuple[int, str]]:
        results = {}
        for target in self.get_cleanup_targets():
            tid = target["id"]
            if tid == "winsxs":
                results[tid] = (0, "Estimate unavailable (DISM)")
                continue

            path = target["path"]
            total_size = 0
            if path and os.path.exists(path):
                try:
                    for root, dirs, files in os.walk(path):
                        for f in files:
                            try:
                                fp = os.path.join(root, f)
                                if not os.path.islink(fp):
                                    total_size += os.path.getsize(fp)
                            except Exception:
                                continue
                except Exception:
                    pass
            results[tid] = (total_size, self.format_bytes(total_size))
        return results

    def execute_cleanup(self, selected_ids: List[str]) -> Tuple[int, str, int]:
        targets = {t["id"]: t for t in self.get_cleanup_targets()}
        total_freed = 0
        total_failures = 0

        for cid in selected_ids:
            if cid not in targets:
                self.log(f"Skipping unknown cleanup target: {cid}", "WARNING")
                total_failures += 1
                continue
            target = targets[cid]

            # Special handler for WinSxS Component Store via DISM
            if cid == "winsxs":
                self.log("Starting Windows Component Store (WinSxS) reduction via DISM...", "INFO")
                code, out = self.run_cmd("DISM.exe /Online /Cleanup-Image /StartComponentCleanup")
                if code == 0:
                    self.log("DISM component cleanup completed. Reclaimed bytes are not reported by DISM.", "SUCCESS")
                else:
                    self.log(f"DISM component cleanup failed with exit code {code}: {out}", "ERROR")
                    total_failures += 1
                continue

            path = target["path"]
            self.log(f"Cleaning {target['name']}...", "INFO")
            if not path or not os.path.exists(path):
                continue

            freed_for_target, failures = self._remove_cleanup_contents(path)
            total_freed += freed_for_target
            total_failures += failures
            level = "WARNING" if failures else "SUCCESS"
            self.log(
                f"Cleaned {target['name']}: {self.format_bytes(freed_for_target)} of file data deleted successfully."
                + (f" {failures} item(s) could not be removed." if failures else ""),
                level
            )

        level = "WARNING" if total_failures else "SUCCESS"
        self.log(
            f"Deep Clean complete. Confirmed file data deleted: {self.format_bytes(total_freed)}."
            + (f" {total_failures} item(s) or operation(s) failed." if total_failures else ""),
            level
        )
        return total_freed, self.format_bytes(total_freed), total_failures

    def _remove_cleanup_contents(self, path: str) -> Tuple[int, int]:
        """Remove a directory's contents without following links; count only successful file deletions."""
        freed = 0
        failures = 0

        try:
            entries = list(os.scandir(path))
        except OSError as exc:
            self.log(f"Could not list cleanup directory {path}: {exc}", "WARNING")
            return 0, 1

        for entry in entries:
            try:
                if entry.is_symlink():
                    os.unlink(entry.path)
                elif entry.is_file(follow_symlinks=False):
                    size = entry.stat(follow_symlinks=False).st_size
                    os.remove(entry.path)
                    freed += size
                elif entry.is_dir(follow_symlinks=False):
                    child_freed, child_failures = self._remove_cleanup_contents(entry.path)
                    freed += child_freed
                    failures += child_failures
                    try:
                        os.rmdir(entry.path)
                    except OSError as exc:
                        failures += 1
                        self.log(f"Could not remove cleanup directory {entry.path}: {exc}", "WARNING")
            except OSError as exc:
                failures += 1
                self.log(f"Could not remove cleanup item {entry.path}: {exc}", "WARNING")

        return freed, failures

    @staticmethod
    def format_bytes(b: int) -> str:
        if b < 1024:
            return f"{b} B"
        elif b < 1024 ** 2:
            return f"{b / 1024:.1f} KB"
        elif b < 1024 ** 3:
            return f"{b / (1024 ** 2):.1f} MB"
        else:
            return f"{b / (1024 ** 3):.2f} GB"

    # -------------------------------------------------------------
    # 9. WinGet Package Updater
    # -------------------------------------------------------------
    def ensure_winget_prerequisites(self) -> bool:
        """Bootstraps NuGet and Microsoft.WinGet.Client package providers if missing."""
        self.log("Verifying WinGet Package Provider prerequisites...", "INFO")
        ps = """
        try {
            if (-not (Get-PackageProvider -Name NuGet -ErrorAction SilentlyContinue)) {
                Install-PackageProvider -Name NuGet -MinimumVersion 2.8.5.201 -Force -ErrorAction Stop | Out-Null
            }
            if (-not (Get-Module -ListAvailable -Name Microsoft.WinGet.Client)) {
                Install-Module -Name Microsoft.WinGet.Client -Force -ErrorAction Stop | Out-Null
            }
            Write-Output "OK"
        } catch {
            Write-Output "ERR"
        }
        """
        c, out = self.run_ps(ps)
        return "OK" in out

    def check_winget_updates(self) -> Tuple[bool, str]:
        self.log("Querying WinGet for upgradable packages...", "INFO")
        c, out = self.run_cmd("winget upgrade --include-unknown")
        if c == 0:
            self.log("WinGet query completed.", "SUCCESS")
            return True, out
        else:
            self.log("WinGet query returned an error. Verifying prerequisites...", "WARNING")
            self.ensure_winget_prerequisites()
            c2, out2 = self.run_cmd("winget upgrade --include-unknown")
            return (c2 == 0), (out2 if c2 == 0 else out)

    def run_winget_upgrade_all(self) -> Tuple[int, str]:
        self.log("Starting bulk application upgrade via WinGet...", "INFO")
        self.ensure_winget_prerequisites()
        cmd = "winget upgrade --all --include-unknown --accept-source-agreements --accept-package-agreements --silent"
        c, out = self.run_cmd(cmd)
        if c == 0:
            self.log("All packages upgraded successfully.", "SUCCESS")
        else:
            self.log(f"WinGet upgrade completed with status {c}.", "INFO")
        return c, out

    def run_cleanmgr_sagerun(self, timeout_seconds: int = 1800) -> bool:
        """Configures cleanmgr VolumeCaches group 69 and runs with a timeout watchdog."""
        self.log(f"Launching CleanMgr with {timeout_seconds}s timeout watchdog...", "INFO")
        group_no = "StateFlags0069"
        root_key = r"SOFTWARE\Microsoft\Windows\CurrentVersion\Explorer\VolumeCaches"
        caches = [
            "Active Setup Temp Folders", "BranchCache", "Content Indexer Cleaner",
            "Delivery Optimization Files", "Diagnostic Data Viewer database Files",
            "D3D Shader Cache", "Downloaded Program Files", "Internet Cache Files",
            "Language Pack", "Offline Pages Files", "Old Chkdsk Files",
            "Recycle Bin", "ServicePack Cleanup", "Setup Log Files",
            "System error memory dump files", "System error minidump files",
            "Temporary Files", "Temporary Setup Files", "Thumbnail Cache",
            "Update Cleanup", "Windows Defender", "Windows Error Reporting Files",
            "Windows Upgrade Log Files"
        ]
        for cache in caches:
            self.set_reg(winreg.HKEY_LOCAL_MACHINE, f"{root_key}\\{cache}", group_no, 2, winreg.REG_DWORD)

        ps_watchdog = f"""
        $timeout = {timeout_seconds};
        Start-Process cleanmgr.exe -ArgumentList '/sagerun:69' -ErrorAction SilentlyContinue
        $sw = [Diagnostics.Stopwatch]::StartNew();
        while ($sw.Elapsed.TotalSeconds -lt $timeout) {{
            $p = Get-Process -Name cleanmgr -ErrorAction SilentlyContinue;
            if (-not $p) {{ exit 0 }};
            Start-Sleep -Seconds 3;
        }};
        $p = Get-Process -Name cleanmgr -ErrorAction SilentlyContinue;
        if ($p) {{ $p | Stop-Process -Force -ErrorAction SilentlyContinue; exit 2 }};
        exit 0;
        """
        c, _ = self.run_ps(ps_watchdog)
        if c == 0:
            self.log("CleanMgr execution completed successfully.", "SUCCESS")
            return True
        elif c == 2:
            self.log("CleanMgr exceeded timeout and was terminated safely.", "WARNING")
            return True
        return False

    # -------------------------------------------------------------
    # Quick System Utilities
    # -------------------------------------------------------------
    def flush_dns(self) -> bool:
        self.log("Flushing DNS Resolver Cache...", "INFO")
        c, _ = self.run_cmd("ipconfig /flushdns")
        if c == 0:
            self.log("DNS cache flushed successfully.", "SUCCESS")
            return True
        return False

    def restart_explorer(self) -> bool:
        self.log("Restarting Windows Explorer shell...", "INFO")
        self.run_cmd("taskkill /f /im explorer.exe")
        subprocess.Popen(["explorer.exe"], creationflags=CREATE_NO_WINDOW)
        self.log("Windows Explorer restarted.", "SUCCESS")
        return True
